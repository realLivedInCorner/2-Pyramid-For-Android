//! **转换产物元数据（`2pyr-gen.json`）**：纯函数构造 + 序列化。
//!
//! ## 这个文件是什么
//!
//! 每次资源包转换成功后，在**产物 zip / 输出目录的根**写一份 `2pyr-gen.json`，
//! 记录"这份包是由哪一版工具、用哪些开关、从什么格式转成什么格式、什么时候转的"。
//! 它只服务两件事：
//!
//! 1. **可追溯**：转换产物经常被二次分发。没有过程信息时，"这份包是哪一版、
//!    用什么参数转的"只能靠猜，出问题无法复现；
//! 2. **排障**：用户反馈"转换后黑紫/丢贴图"时，日志不一定还在，产物里的参数记录
//!    能直接回答"当时 CIT 转换开没开、shader 适配开没开"。
//!
//! ## 隐私边界（硬约束，改字段前先读）
//!
//! **只收录转换参数，不收录任何个人信息**：没有源/输出路径、没有 Windows 用户名、
//! 没有机器名 / 硬件 ID / UUID / 网络信息。这个文件会随产物包被分发到别人手里，
//! 写入本机信息等于泄漏。
//!
//! 因此 [`build`] 的入参只有标量格式号、目标标签和六个开关——**结构上就无从拿到
//! 路径或用户名**。这条承诺与 `legal/EULA.md`、`legal/PRIVACY.md`（中英各两份）
//! 里披露的字段清单是同一份，改动任何一侧都要同步四份法律文档。
//!
//! ## 客户端会不会读它
//!
//! 不会。文件放在包根，Minecraft 的 Java 版资源包只读取 `pack.mcmeta` 与
//! `assets/`，未知根条目被忽略（这与 OptiFine 的 `optifine/`、`shaders/`、
//! 各种工具自己塞的说明文件同理）。写了不影响加载，删了也不影响。
//!
//! ## 谁在什么位置写
//!
//! * 构造：`pack::version_converter::process_zip_timed`（只在 Java 目标，用户开启时）；
//! * 落盘：`native_run::run_native` 的 `tail`（与改写 `pack.mcmeta` 同一个事务），
//!   因此 `Output::Zip` 与 `Output::Dir` 两条路径都天然覆盖；
//! * 关闭：转换页开关（配置字段 `write_gen_metadata`，默认开）。关闭后
//!   `MixedRunOptions::gen_metadata` 为 `None`，驱动里一行都不写。
//!
//! ## 体积与格式
//!
//! 2 空格缩进的 JSON（给人读，不压缩），键序由结构体声明顺序固定（不依赖
//! `serde_json` 的 map 排序特性），末尾补一个换行便于 `git diff` / `jq`。
//! 实测序列化后 **< 1 KB**（单测钉住 1024 字节上限）——对一个动辄几十 MB 的资源包
//! 可以忽略，但足以把整条转换链的信息说清楚。

/// 产物根目录里的文件名（对外契约，勿改：第三方脚本可能按这个名字识别）。
pub const FILE_NAME: &str = "2pyr-gen.json";

/// 生成器标识。
const GENERATOR: &str = "2-Pyramid";
/// 工具版本（`Cargo.toml` 的 `version`，编译期注入）。
const GENERATOR_VERSION: &str = env!("CARGO_PKG_VERSION");
/// 构建号（`build.rs` 注入：release 为纯数字，debug 为 `dev.N`）。
const GENERATOR_BUILD: &str = env!("BUILD_NUMBER");
/// 中性说明行（中英双语：产物可能流到中文或英文用户手里）。
const NOTICE: &str = "Generated by 2-Pyramid to record this conversion's parameters. \
Minecraft does not read this file. 由 2-Pyramid 生成，用于记录本次转换参数；\
Minecraft 客户端不读取本文件；可在转换页关闭写入。";

/// 本次转换的六个开关（与转换页一一对应，顺序即 JSON 里的键序）。
///
/// 这些是**用户选择**，不是工具自作主张；记录它们才能回答
/// "这份产物的 CIT / shader 处理到底开没开"。
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, serde::Serialize)]
pub struct GenOptions {
    /// 图层修复（透明层边缘）。
    pub fix_alpha_layers: bool,
    /// 着色器适配（按目标版本改写 shaders）。
    pub adapt_shaders: bool,
    /// 彻底删除 shaders（破坏性）。
    pub delete_shaders: bool,
    /// 旧 `overrides` → 1.21.4+ `items/*.json`。
    pub convert_item_definitions: bool,
    /// OptiFine CIT → 1.21.4+ 物品定义。
    pub convert_cit: bool,
    /// 彻底删除 CIT 源目录（破坏性）。
    pub delete_cit: bool,
}

/// `2pyr-gen.json` 的内容。
///
/// 字段清单是**对外契约**（法律文档披露的同一份），不要随手加字段：
/// 新增字段 = 新增披露义务。字段名用 snake_case，键序由声明顺序固定。
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
pub struct GenMetadata {
    /// 固定 `"2-Pyramid"`。
    pub generator: &'static str,
    /// 工具版本，如 `"2.203.0"`。
    pub generator_version: &'static str,
    /// 构建号，如 `"22030"`（debug 构建为 `"dev.22030"`）。
    pub generator_build: &'static str,
    /// 生成时间：UTC、RFC3339、秒级、`Z` 结尾，如 `"2026-10-24T14:31:49Z"`。
    pub generated_at: String,
    /// 源包 `pack.mcmeta` 读到的 pack_format。
    pub source_pack_format: u32,
    /// 目标 pack_format。
    pub target_pack_format: u32,
    /// 目标版本标签（如 `"Java 1.21.9-1.21.10"`）。
    ///
    /// 拿不到可靠标签时**整个键省略**（`skip_serializing_if`），绝不写 `"Unknown"`
    /// 之类的占位值——占位值会被当成版本信息误读。源标签同理不写（无法可靠取得）。
    #[serde(skip_serializing_if = "Option::is_none")]
    pub target_label: Option<String>,
    /// 本次转换的六个开关。
    pub options: GenOptions,
    /// 中性说明行（告诉拿到包的人这是什么文件、客户端不读它）。
    pub notice: &'static str,
}

/// 当前时间的 UTC RFC3339 秒级表示（`Z` 结尾，无小数秒）。
///
/// 为什么截到秒：这个字段是给人读的排障信息，秒级足够；小数秒只会让同一次转换
/// 在日志与产物里出现两个不同写法。
pub fn now_rfc3339_seconds() -> String {
    chrono::Utc::now().to_rfc3339_opts(chrono::SecondsFormat::Secs, true)
}

/// 构造元数据（`generated_at` 取当前时间）。
///
/// * `source_pack_format`：转换开始时从源包 `pack.mcmeta` 读到的格式；
/// * `target_pack_format`：用户选择的目标格式；
/// * `target_label`：目标版本标签；拿不到传 `None`（键会被省略）；
/// * `options`：本次转换的六个开关。
pub fn build(
    source_pack_format: u32,
    target_pack_format: u32,
    target_label: Option<&str>,
    options: GenOptions,
) -> GenMetadata {
    build_at(
        source_pack_format,
        target_pack_format,
        target_label,
        options,
        now_rfc3339_seconds(),
    )
}

/// 注入时间戳的构造函数：让"除时间外可复现"能被单测直接验证。
///
/// `target_label` 在这里做最后一道防呆：空串/纯空白/`"Unknown"` 一律视为拿不到
/// （不写占位值）；正常标签只做 trim，不改写内容。
pub fn build_at(
    source_pack_format: u32,
    target_pack_format: u32,
    target_label: Option<&str>,
    options: GenOptions,
    generated_at: String,
) -> GenMetadata {
    let target_label = target_label
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .filter(|s| !s.eq_ignore_ascii_case("unknown"))
        .map(str::to_string);
    GenMetadata {
        generator: GENERATOR,
        generator_version: GENERATOR_VERSION,
        generator_build: GENERATOR_BUILD,
        generated_at,
        source_pack_format,
        target_pack_format,
        target_label,
        options,
        notice: NOTICE,
    }
}

impl GenMetadata {
    /// 契约字段的 JSON 值视图（字段齐全、键序固定）。
    ///
    /// 结构体只有标量、字符串与嵌套结构体，序列化不会失败；这里返回 `Value`
    /// 而不是 `Result`，避免调用方围着一条不可能的分支写代码。
    ///
    /// 生产写入路径只走 [`Self::to_json_bytes`]（它直接产出最终字节）；本方法是
    /// 单测与（未来）报告的读值入口，非 test 构建里没有调用者。
    #[allow(dead_code)]
    pub fn to_json(&self) -> serde_json::Value {
        serde_json::to_value(self).expect("GenMetadata 只含标量/字符串，序列化不可失败")
    }

    /// 2 空格缩进的 UTF-8 JSON，末尾补换行。
    ///
    /// 键序由结构体字段声明顺序决定，因此同一份内容**逐字节可复现**（除时间外）。
    pub fn to_json_bytes(&self) -> Result<Vec<u8>, String> {
        let mut bytes = serde_json::to_vec_pretty(self)
            .map_err(|e| format!("serialize {FILE_NAME}: {e}"))?;
        bytes.push(b'\n');
        Ok(bytes)
    }

    /// 文本形式（日志/测试用；生产写入只走 [`Self::to_json_bytes`]）。
    #[allow(dead_code)]
    pub fn to_json_string(&self) -> Result<String, String> {
        String::from_utf8(self.to_json_bytes()?).map_err(|e| format!("{FILE_NAME} 必须是 UTF-8: {e}"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 一份字段值全部可区分的样本（布尔开关有真有假，避免"全 false 恰好测不出来"）。
    fn sample_options() -> GenOptions {
        GenOptions {
            fix_alpha_layers: true,
            adapt_shaders: true,
            delete_shaders: false,
            convert_item_definitions: true,
            convert_cit: false,
            delete_cit: false,
        }
    }

    fn sample() -> GenMetadata {
        build_at(
            34,
            69,
            Some("Java 1.21.9-1.21.10"),
            sample_options(),
            "2026-10-24T14:31:49Z".to_string(),
        )
    }

    /// **字段集合与值必须精确符合契约**（多一个字段 = 多一份披露义务）。
    #[test]
    fn contract_fields_and_values_are_pinned() {
        let v = sample().to_json();

        // 顶层字段集合必须**恰好**是这些（顺序另有用例守；这里集合相等即可）
        let mut keys: Vec<&str> = v
            .as_object()
            .expect("顶层必须是对象")
            .keys()
            .map(|k| k.as_str())
            .collect();
        keys.sort_unstable();
        assert_eq!(
            keys,
            vec![
                "generated_at",
                "generator",
                "generator_build",
                "generator_version",
                "notice",
                "options",
                "source_pack_format",
                "target_label",
                "target_pack_format",
            ],
            "字段集合与对外契约不一致：{keys:?}"
        );

        assert_eq!(v["generator"], "2-Pyramid");
        assert_eq!(v["generator_version"], env!("CARGO_PKG_VERSION"));
        assert_eq!(v["generator_build"], env!("BUILD_NUMBER"));
        assert_eq!(v["generated_at"], "2026-10-24T14:31:49Z");
        assert_eq!(v["source_pack_format"], 34);
        assert_eq!(v["target_pack_format"], 69);
        assert_eq!(v["target_label"], "Java 1.21.9-1.21.10");
        assert_eq!(v["options"]["fix_alpha_layers"], true);
        assert_eq!(v["options"]["adapt_shaders"], true);
        assert_eq!(v["options"]["delete_shaders"], false);
        assert_eq!(v["options"]["convert_item_definitions"], true);
        assert_eq!(v["options"]["convert_cit"], false);
        assert_eq!(v["options"]["delete_cit"], false);
        assert!(
            v["notice"].as_str().map(|s| !s.is_empty()).unwrap_or(false),
            "notice 必须是非空字符串"
        );

        // options 的键集合同样钉住（六个开关一个不多一个不少）
        let mut opt_keys: Vec<&str> = v["options"]
            .as_object()
            .expect("options 必须是对象")
            .keys()
            .map(|k| k.as_str())
            .collect();
        opt_keys.sort_unstable();
        assert_eq!(
            opt_keys,
            vec![
                "adapt_shaders",
                "convert_cit",
                "convert_item_definitions",
                "delete_cit",
                "delete_shaders",
                "fix_alpha_layers",
            ],
            "options 键集合与契约不一致：{opt_keys:?}"
        );
    }

    /// **序列化：2 空格缩进、可解析、可复现（除时间外）、体积 < 1 KB。**
    #[test]
    fn serialized_json_is_stable_pretty_and_small() {
        let meta = sample();
        let text = meta.to_json_string().expect("serialize");

        // 2 空格缩进（`serde_json::to_vec_pretty` 的默认缩进）
        assert!(text.contains("\n  \"generator\""), "必须是 2 空格缩进的 JSON：{text}");
        // 末尾换行：文本文件习惯，git diff / jq 更友好
        assert!(text.ends_with("\n"), "末尾必须有一个换行：{text:?}");
        // 可被标准 JSON 解析器重新解析
        let reparsed: serde_json::Value = serde_json::from_str(&text).expect("必须是合法 JSON");
        assert_eq!(reparsed, meta.to_json(), "解析回来的值必须与 to_json 一致");
        // 体积上限：契约写着"只有几百字节"，用断言防止以后加出大字段
        assert!(
            text.len() < 1024,
            "2pyr-gen.json 必须保持 < 1 KB，实际 {} 字节：{text}",
            text.len()
        );

        // 除时间外逐字节可复现：同一份内容 + 同一时间 → 完全相同的字节
        let again = build_at(
            34,
            69,
            Some("Java 1.21.9-1.21.10"),
            sample_options(),
            meta.generated_at.clone(),
        );
        assert_eq!(
            meta.to_json_bytes().expect("bytes"),
            again.to_json_bytes().expect("bytes"),
            "相同输入与时间必须产出逐字节相同的 JSON（键序/缩进确定）"
        );
    }

    /// **时间戳：UTC、RFC3339、秒级**。
    #[test]
    fn generated_at_is_utc_rfc3339_with_second_precision() {
        let ts = now_rfc3339_seconds();
        assert!(ts.ends_with('Z'), "必须是 UTC 的 Z 后缀：{ts}");
        let parsed = chrono::DateTime::parse_from_rfc3339(&ts).expect("必须是 RFC3339");
        assert_eq!(parsed.offset().local_minus_utc(), 0, "必须是 UTC：{ts}");
        assert_eq!(parsed.timestamp_subsec_nanos(), 0, "必须是秒级（无小数秒）：{ts}");
        assert_eq!(ts.len(), 20, "秒级 RFC3339 的固定长度是 20：{ts:?}");

        // build() 走的是同一个时钟函数
        let built = build(15, 34, Some("Java 1.21-1.21.1"), GenOptions::default());
        let parsed = chrono::DateTime::parse_from_rfc3339(&built.generated_at)
            .expect("build() 的 generated_at 也必须是 RFC3339");
        assert_eq!(parsed.offset().local_minus_utc(), 0);
    }

    /// **无个人信息**：字段结构上就没有路径/用户名/机器信息的入口，这里再加两道
    /// 回归网——① 字段名不许出现个人信息类词汇；② 序列化文本里不许出现本机的
    /// 用户名、用户目录、临时目录。
    ///
    /// 为什么值得单测：这个文件随产物**分发到别人机器**，一旦有人"顺手"加一个
    /// `source_path` 字段，单靠代码评审很容易漏。
    #[test]
    fn no_personal_information_fields_or_values() {
        let meta = build_at(
            15,
            69,
            Some("Java 1.21.9-1.21.10"),
            sample_options(),
            "2026-10-24T14:31:49Z".to_string(),
        );
        let v = meta.to_json();

        // ① 字段名（含嵌套 options）不许命中个人信息类词汇
        let forbidden_keys = [
            "path", "dir", "user", "machine", "host", "uuid", "email", "ip", "pc",
            "computer", "home", "os", "window", "account", "hardware",
        ];
        fn check_keys(v: &serde_json::Value, forbidden: &[&str]) {
            match v {
                serde_json::Value::Object(map) => {
                    for (k, child) in map {
                        let lower = k.to_ascii_lowercase();
                        for bad in forbidden {
                            assert!(
                                !lower.contains(bad),
                                "字段名 `{k}` 命中个人信息类词汇 `{bad}`——2pyr-gen 不得收录个人信息"
                            );
                        }
                        check_keys(child, forbidden);
                    }
                }
                serde_json::Value::Array(items) => {
                    for item in items {
                        check_keys(item, forbidden);
                    }
                }
                _ => {}
            }
        }
        check_keys(&v, &forbidden_keys);

        // ② 值里不许出现本机身份信息（用户名 / 用户主目录 / 临时目录）
        let text = meta.to_json_string().expect("serialize");
        for env_key in ["USERNAME", "USERPROFILE", "COMPUTERNAME"] {
            if let Ok(value) = std::env::var(env_key) {
                if value.len() >= 3 {
                    assert!(
                        !text.contains(&value),
                        "2pyr-gen.json 里出现了本机 {env_key} 的值：{text}"
                    );
                }
            }
        }
        for dir in [std::env::temp_dir(), dirs::home_dir().unwrap_or_default()] {
            if let Some(dir) = dir.to_str() {
                if dir.len() >= 3 {
                    assert!(
                        !text.contains(dir),
                        "2pyr-gen.json 里出现了本机目录 `{dir}`：{text}"
                    );
                }
            }
        }
    }

    /// **`target_label`：拿不到就整个键省略，绝不写占位值。**
    ///
    /// 契约允许"标签拿不到"，但明确禁止 `"Unknown"` 之类的假值——它会被下游当成
    /// 真实版本信息。源标签同理不写（`source_pack_format` 已足够定位）。
    #[test]
    fn target_label_is_omitted_when_unreliable() {
        let omit = |label: Option<&str>| {
            build_at(15, 34, label, GenOptions::default(), "2026-10-24T14:31:49Z".to_string())
                .to_json()
        };

        assert!(omit(None).get("target_label").is_none(), "None 必须省略键");
        assert!(omit(Some("")).get("target_label").is_none(), "空串必须省略键");
        assert!(omit(Some("   ")).get("target_label").is_none(), "空白必须省略键");
        assert!(
            omit(Some("Unknown")).get("target_label").is_none(),
            "`Unknown` 是占位符不是版本，必须省略键"
        );
        assert_eq!(
            omit(Some("  Java 1.21.9-1.21.10  "))["target_label"],
            "Java 1.21.9-1.21.10",
            "正常标签只 trim，不改写内容"
        );
    }
}
